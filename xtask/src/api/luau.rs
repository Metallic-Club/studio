//! The Luau type definitions (`api/metallic.d.luau`), generated from the API dump in the definitions-file syntax
//! luau-lsp reads (`luau-lsp analyze --definitions=@metallic=api/metallic.d.luau`, or the editor setting
//! `luau-lsp.types.definitionFiles`).
//!
//! The file is the hand-written prelude (`luau_prelude.d.luau`: data types, signals, globals) followed by what this
//! module generates from the dump:
//!
//! - **Enums:** each enum `X` is an item type `EnumX` (extending `EnumItem`) and a table type `EnumX_INTERNAL`
//!   (extending `Enum`) holding the items, reached as `Enum.X`. This is luau-lsp's own convention: under its
//!   `standard` platform scripts annotate an item as `EnumX`; under its `roblox` platform luau-lsp renames the
//!   types so they read `Enum.X`.
//! - **Classes:** `declare extern type Part extends BasePart with ... end`, with the class's own properties, the
//!   properties of the components it adds, its callbacks, signals and methods. Read-only properties are `read`, and
//!   callbacks `write` (scripts may only assign them). A signal is a `ScriptSignal<params...>` property.
//! - **`Instance.new`**: one overload per creatable class, keyed by the class name as a string literal type, so
//!   `Instance.new("Part")` is a `Part`.
//!
//! The file targets luau-lsp's `standard` platform and its default type solver; CI checks it with luau-lsp 1.70.1.
//! luau-lsp's opt-in new solver (`LuauSolverV2`) gives up on an overload set of more than about ten functions ("too
//! complex to typecheck") and then ignores the whole file. Roblox's own definitions avoid that with a luau-lsp
//! special case for Roblox's `Instance.new`, which a `standard` definitions file cannot use.
//!
//! Two things the dump holds cannot be written in Luau's class syntax, so the definitions approximate them:
//!
//! - a member hidden by a subclass (`hides`) stays visible on it, inherited from the parent (a comment marks it);
//! - `Changed` on a class that passes the new value of a property (`changed_passes_value`) is re-declared on each
//!   class that declares that property, with the property's type.

use std::collections::{BTreeSet, HashMap};
use std::fmt::Write as _;

use metallic_script::ApiDump;
use metallic_script::api_dump::{ApiClass, ApiComponent, ApiParam, ApiProperty, ApiType};

/// The data types, signals and globals the Luau backend builds by hand (see the file's header).
const PRELUDE: &str = include_str!("luau_prelude.d.luau");

/// The signal the Luau backend gives every instance for changes of one property (`crates/luau/src/shared.rs`); it
/// is not a registry member, so the root class gets it here.
const PROPERTY_CHANGED_SIGNAL: &str = "    --- Fires after the named property changes.\n    function GetPropertyChangedSignal(self, property: string): \
     ScriptSignal<>\n";

/// The whole definitions file for `dump`.
pub(crate) fn definitions(dump: &ApiDump) -> String {
    let mut out = String::new();
    out.push_str(&format!(
        "-- Luau type definitions for Metallic's scripting API, in luau-lsp's definitions-file syntax.\n\
         -- GENERATED by `cargo xtask api-dump` from api/api-dump.json (format {}). Do not edit: change the class\n\
         -- files (crates/classes) or xtask/src/api/luau_prelude.d.luau, then run the command again.\n\
         --\n\
         -- luau-lsp: `luau-lsp analyze --platform=standard --definitions=@metallic=api/metallic.d.luau <files>`, or\n\
         -- `luau-lsp.platform.type = \"standard\"` and `luau-lsp.types.definitionFiles` in an editor.\n\n",
        dump.format
    ));
    out.push_str(PRELUDE);
    out.push('\n');
    section(&mut out, "Enums (generated)");
    enums(&mut out, dump);
    section(&mut out, "Classes (generated)");
    let generator = Classes::new(dump);
    for class in &dump.classes {
        generator.class(&mut out, class);
    }
    instance_new(&mut out, dump);
    out
}

fn section(out: &mut String, title: &str) {
    let rule = "-".repeat(117);
    let _ = write!(out, "{rule}\n-- {title}\n{rule}\n\n");
}

/// `--- text` lines for a description, indented by `indent`; nothing for an empty one.
fn doc(out: &mut String, indent: &str, description: &str) {
    for line in description.lines() {
        let line = line.trim_end();
        if line.is_empty() {
            let _ = writeln!(out, "{indent}---");
        } else {
            let _ = writeln!(out, "{indent}--- {line}");
        }
    }
}

fn enums(out: &mut String, dump: &ApiDump) {
    for e in &dump.enums {
        doc(out, "", &e.description);
        let _ = writeln!(out, "declare extern type Enum{} extends EnumItem with end", e.name);
        let _ = writeln!(out, "declare extern type Enum{}_INTERNAL extends Enum with", e.name);
        for item in &e.items {
            let _ = writeln!(out, "    read {}: Enum{}", item.name, e.name);
        }
        let _ = writeln!(out, "    function GetEnumItems(self): {{ Enum{} }}", e.name);
        out.push_str("end\n\n");
    }
    out.push_str("--- Every engine enum, such as `Enum.Material`.\ndeclare Enum: {\n");
    for e in &dump.enums {
        let _ = writeln!(out, "    {}: Enum{}_INTERNAL,", e.name, e.name);
    }
    out.push_str("}\n\n");
}

/// The Luau type of a value of type `ty`, such as `BasePart?`, `{Instance}` or `EnumMaterial`.
///
/// A variadic writes as the pack `...T` and a tuple as `(A, B)`, which is right where they may appear: a parameter
/// list's end and a return type.
pub(crate) fn luau_type(ty: &ApiType) -> String {
    match ty {
        ApiType::Bool => "boolean".to_owned(),
        ApiType::Int | ApiType::Number => "number".to_owned(),
        ApiType::String => "string".to_owned(),
        ApiType::Vector2 => "Vector2".to_owned(),
        ApiType::Vector3 => "Vector3".to_owned(),
        ApiType::CFrame => "CFrame".to_owned(),
        ApiType::Color3 => "Color3".to_owned(),
        ApiType::Enum(name) => format!("Enum{name}"),
        ApiType::Class(name) => name.clone(),
        ApiType::Any => "any".to_owned(),
        ApiType::Nil => "nil".to_owned(),
        ApiType::Optional(inner) => optional(inner),
        ApiType::Array(item) => format!("{{{}}}", luau_type(item)),
        ApiType::Map(key, value) => format!("{{[{}]: {}}}", luau_type(key), luau_type(value)),
        ApiType::Variadic(item) => format!("...{}", luau_type(item)),
        ApiType::Tuple(items) => format!("({})", list(items.iter().map(luau_type))),
        ApiType::Function => "(...any) -> ...any".to_owned(),
    }
}

/// `T?`, without doubling the `?` of a type that already accepts nil, and with a function type in parentheses
/// (`?` binds tighter than `->`).
fn optional(inner: &ApiType) -> String {
    match inner {
        ApiType::Any | ApiType::Nil | ApiType::Optional(_) => luau_type(inner),
        ApiType::Function => format!("({})?", luau_type(inner)),
        _ => format!("{}?", luau_type(inner)),
    }
}

fn list(items: impl Iterator<Item = String>) -> String {
    items.collect::<Vec<_>>().join(", ")
}

/// One parameter of a declared method: `name: T`, `name: T?` when it may be left out, `...: T` for a variadic.
fn param(p: &ApiParam) -> String {
    match &p.ty {
        ApiType::Variadic(item) => format!("...: {}", luau_type(item)),
        ty if p.optional => format!("{}: {}", p.name, optional(ty)),
        ty => format!("{}: {}", p.name, luau_type(ty)),
    }
}

/// One parameter inside a function type: like [`param`], but a variadic is the bare pack `...T`.
fn function_type_param(p: &ApiParam) -> String {
    match &p.ty {
        ApiType::Variadic(item) => format!("...{}", luau_type(item)),
        _ => param(p),
    }
}

/// A return type: `()` for none, `(A, B)` for several, `...any` when it is not declared. A lone function type is
/// parenthesized so its own `->` does not swallow what follows.
pub(crate) fn returns(ty: Option<&ApiType>) -> String {
    match ty {
        None => "...any".to_owned(),
        Some(ApiType::Function) => format!("({})", luau_type(&ApiType::Function)),
        Some(ty) => luau_type(ty),
    }
}

/// The type arguments of a signal whose listeners receive `params`: `ScriptSignal<Instance, string?>`,
/// `ScriptSignal<>` for none, `ScriptSignal<...any>` when they are not declared.
pub(crate) fn signal_type(params: Option<&[ApiParam]>) -> String {
    let Some(params) = params else {
        return "ScriptSignal<...any>".to_owned();
    };
    let args = params.iter().map(|p| match &p.ty {
        ApiType::Variadic(_) => luau_type(&p.ty),
        ty if p.optional => optional(ty),
        ty => luau_type(ty),
    });
    format!("ScriptSignal<{}>", list(args))
}

/// The type of a callback slot: a function with the callback's signature, or nil to clear it.
pub(crate) fn callback_type(params: Option<&[ApiParam]>, ret: Option<&ApiType>) -> String {
    let params = match params {
        Some(params) => list(params.iter().map(function_type_param)),
        None => "...any".to_owned(),
    };
    format!("(({params}) -> {})?", returns(ret))
}

/// What generating a class needs to know about the others.
struct Classes<'a> {
    by_name: HashMap<&'a str, &'a ApiClass>,
    components: HashMap<&'a str, &'a ApiComponent>,
}

impl<'a> Classes<'a> {
    fn new(dump: &'a ApiDump) -> Self {
        Self {
            by_name: dump.classes.iter().map(|c| (c.name.as_str(), c)).collect(),
            components: dump.components.iter().map(|c| (c.name.as_str(), c)).collect(),
        }
    }

    /// The class's ancestors, nearest first, without the class itself.
    fn ancestors(&self, class: &'a ApiClass) -> Vec<&'a ApiClass> {
        let mut chain = Vec::new();
        let mut next = class.parent.as_deref();
        while let Some(name) = next {
            let Some(parent) = self.by_name.get(name) else {
                break;
            };
            // A cycle cannot pass the registry; stop anyway rather than loop.
            if chain.iter().any(|c: &&ApiClass| c.name == parent.name) {
                break;
            }
            chain.push(*parent);
            next = parent.parent.as_deref();
        }
        chain
    }

    /// The property whose value `Changed` passes on this class (its own declaration or the nearest ancestor's).
    fn changed_passes_value(&self, class: &'a ApiClass) -> Option<&'a str> {
        std::iter::once(class)
            .chain(self.ancestors(class))
            .find_map(|c| c.changed_passes_value.as_deref())
    }

    fn class(&self, out: &mut String, class: &'a ApiClass) {
        doc(out, "", &class.description);
        match &class.parent {
            Some(parent) => {
                let _ = writeln!(out, "declare extern type {} extends {parent} with", class.name);
            }
            None => {
                let _ = writeln!(out, "declare extern type {} with", class.name);
            }
        }
        for hidden in &class.hides {
            let _ = writeln!(
                out,
                "    -- `{hidden}` is hidden on {} (luau-lsp cannot remove an inherited member).",
                class.name
            );
        }

        let inherited: BTreeSet<&str> = self
            .ancestors(class)
            .iter()
            .flat_map(|c| c.components.iter().map(String::as_str))
            .collect();
        for name in &class.components {
            if inherited.contains(name.as_str()) {
                continue;
            }
            if let Some(component) = self.components.get(name.as_str()) {
                for prop in &component.properties {
                    property(out, prop);
                }
            }
        }
        for prop in &class.properties {
            property(out, prop);
        }

        for callback in &class.callbacks {
            doc(out, "    ", &callback.description);
            let ty = callback_type(callback.params.as_deref(), callback.returns.as_ref());
            let _ = writeln!(out, "    write {}: {ty}", callback.name);
        }

        // `Changed` passes the new value of a property this class declares: re-declare it with that type.
        let changed_value = self
            .changed_passes_value(class)
            .and_then(|name| class.properties.iter().find(|p| p.name == name));
        if let Some(prop) = changed_value
            && !class.signals.iter().any(|s| s.name == "Changed")
        {
            let _ = writeln!(
                out,
                "    --- Fires after {} changes, with the new value.\n    Changed: ScriptSignal<{}>",
                prop.name,
                luau_type(&prop.ty)
            );
        }
        for signal in &class.signals {
            doc(out, "    ", &signal.description);
            let ty = match changed_value {
                Some(prop) if signal.name == "Changed" => format!("ScriptSignal<{}>", luau_type(&prop.ty)),
                _ => signal_type(signal.params.as_deref()),
            };
            let _ = writeln!(out, "    {}: {ty}", signal.name);
        }

        if class.parent.is_none() {
            out.push_str(PROPERTY_CHANGED_SIGNAL);
        }
        for method in &class.methods {
            doc(out, "    ", &method.description);
            let params = match &method.params {
                Some(params) => params.iter().map(param).fold(String::new(), |mut s, p| {
                    s.push_str(", ");
                    s.push_str(&p);
                    s
                }),
                None => ", ...: any".to_owned(),
            };
            let _ = writeln!(
                out,
                "    function {}(self{params}): {}",
                method.name,
                returns(method.returns.as_ref())
            );
        }
        out.push_str("end\n\n");
    }
}

fn property(out: &mut String, prop: &ApiProperty) {
    doc(out, "    ", &prop.description);
    let access = if prop.read_only { "read " } else { "" };
    let _ = writeln!(out, "    {access}{}: {}", prop.name, luau_type(&prop.ty));
}

/// `declare Instance: { new: ... }`, one overload per creatable class.
fn instance_new(out: &mut String, dump: &ApiDump) {
    let overloads: Vec<String> = dump
        .classes
        .iter()
        .filter(|c| c.creatable)
        .map(|c| format!("((className: \"{0}\", parent: Instance?) -> {0})", c.name))
        .collect();
    out.push_str("--- Creates instances: `Instance.new(\"Part\", workspace)`.\ndeclare Instance: {\n    new: ");
    if overloads.is_empty() {
        out.push_str("(className: string, parent: Instance?) -> Instance");
    } else {
        out.push_str(&overloads.join("\n        & "));
    }
    out.push_str(",\n}\n");
}

#[cfg(test)]
mod tests {
    use super::*;

    fn class(name: &str) -> ApiType {
        ApiType::Class(name.to_owned())
    }

    fn boxed(ty: ApiType) -> Box<ApiType> {
        Box::new(ty)
    }

    fn p(name: &str, ty: ApiType, optional: bool) -> ApiParam {
        ApiParam {
            name: name.to_owned(),
            ty,
            optional,
        }
    }

    #[test]
    fn types_map_to_luau() {
        let cases = [
            (ApiType::Bool, "boolean"),
            (ApiType::Int, "number"),
            (ApiType::Number, "number"),
            (ApiType::String, "string"),
            (ApiType::Vector2, "Vector2"),
            (ApiType::Vector3, "Vector3"),
            (ApiType::CFrame, "CFrame"),
            (ApiType::Color3, "Color3"),
            (ApiType::Enum("Material".into()), "EnumMaterial"),
            (class("BasePart"), "BasePart"),
            (ApiType::Any, "any"),
            (ApiType::Nil, "nil"),
            (ApiType::Optional(boxed(class("Instance"))), "Instance?"),
            (ApiType::Optional(boxed(ApiType::Any)), "any"),
            (ApiType::Optional(boxed(ApiType::Function)), "((...any) -> ...any)?"),
            (ApiType::Array(boxed(class("Instance"))), "{Instance}"),
            (
                ApiType::Array(boxed(ApiType::Optional(boxed(ApiType::Enum("Material".into()))))),
                "{EnumMaterial?}",
            ),
            (
                ApiType::Map(boxed(ApiType::String), boxed(ApiType::Any)),
                "{[string]: any}",
            ),
            (ApiType::Variadic(boxed(ApiType::Any)), "...any"),
            (ApiType::Tuple(vec![]), "()"),
            (
                ApiType::Tuple(vec![ApiType::CFrame, ApiType::Bool]),
                "(CFrame, boolean)",
            ),
            (ApiType::Function, "(...any) -> ...any"),
        ];
        for (ty, expected) in cases {
            assert_eq!(luau_type(&ty), expected, "{ty:?}");
        }
    }

    #[test]
    fn params_returns_signals_and_callbacks_map_to_luau() {
        assert_eq!(param(&p("name", ApiType::String, false)), "name: string");
        assert_eq!(param(&p("recursive", ApiType::Bool, true)), "recursive: boolean?");
        assert_eq!(param(&p("value", ApiType::Any, true)), "value: any");
        assert_eq!(param(&p("f", ApiType::Function, true)), "f: ((...any) -> ...any)?");
        assert_eq!(
            param(&p("args", ApiType::Variadic(boxed(ApiType::Any)), false)),
            "...: any"
        );

        assert_eq!(returns(None), "...any");
        assert_eq!(returns(Some(&ApiType::Tuple(vec![]))), "()");
        assert_eq!(returns(Some(&ApiType::Function)), "((...any) -> ...any)");
        assert_eq!(returns(Some(&ApiType::Optional(boxed(class("Instance"))))), "Instance?");

        assert_eq!(signal_type(None), "ScriptSignal<...any>");
        assert_eq!(signal_type(Some(&[])), "ScriptSignal<>");
        let params = [
            p("child", class("Instance"), false),
            p("parent", ApiType::Optional(boxed(class("Instance"))), false),
            p("rest", ApiType::Variadic(boxed(ApiType::Any)), false),
        ];
        assert_eq!(signal_type(Some(&params)), "ScriptSignal<Instance, Instance?, ...any>");

        let ret = ApiType::Tuple(vec![ApiType::Bool, ApiType::Number]);
        assert_eq!(
            callback_type(Some(&params[2..]), Some(&ret)),
            "((...any) -> (boolean, number))?"
        );
        assert_eq!(
            callback_type(Some(&params[..1]), Some(&ApiType::Nil)),
            "((child: Instance) -> nil)?"
        );
        assert_eq!(callback_type(None, None), "((...any) -> ...any)?");
    }

    #[test]
    fn classes_get_their_members_components_and_typed_changed() {
        let registry = metallic_classes::shared_registry().unwrap();
        let text = definitions(&ApiDump::from_registry(&registry));
        assert!(text.starts_with("-- Luau type definitions"));
        assert!(text.contains("declare extern type Object with\n"));
        assert!(text.contains("declare extern type Part extends BasePart with\n"));
        assert!(text.contains("function GetPropertyChangedSignal(self, property: string): ScriptSignal<>"));
        assert!(text.contains("function FindFirstChild(self, name: string, recursive: boolean?): Instance?"));
        assert!(text.contains("    read ClassName: string\n"));
        assert!(text.contains("    write OnInvoke: "));
        assert!(text.contains("((className: \"Part\", parent: Instance?) -> Part)"));
        assert!(text.contains("    read Plastic: EnumMaterial\n"));
        // `IntValue.Changed` passes the new number, not a property name.
        let int_value = text
            .split("declare extern type IntValue extends ValueBase with\n")
            .nth(1)
            .and_then(|rest| rest.split("\nend\n").next())
            .unwrap();
        assert!(int_value.contains("Changed: ScriptSignal<number>"), "{int_value}");
    }
}
