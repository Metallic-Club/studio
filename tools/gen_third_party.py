#!/usr/bin/env python3
"""Writes crates/metallic_studio/assets/THIRD_PARTY.md: the Rust crates Studio is built from and
their licences, read from `cargo metadata`. Studio shows the file on its "Third-party licences" screen.

    python -I tools/gen_third_party.py          # rewrite the file
    python -I tools/gen_third_party.py --check  # exit 1 when it is stale

The header line records a hash of Cargo.lock. A Rust test (src/licences.rs) compares it with the
current Cargo.lock, so a dependency change fails CI until this script has been run again.
"""

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "crates" / "metallic_studio" / "assets" / "THIRD_PARTY.md"
STUDIO = "metallic_studio"
MARKER = "cargo-lock-fnv1a64: "


def lock_hash(text):
    """FNV-1a, 64 bit, of Cargo.lock with line endings normalised (mirrored in licences.rs)."""
    h = 0xCBF29CE484222325
    for byte in text.replace("\r\n", "\n").encode("utf-8"):
        h = ((h ^ byte) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return f"{h:016x}"


def shipped_crates(meta):
    """Registry crates reachable from Studio through normal and build dependencies."""
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    packages = {p["id"]: p for p in meta["packages"]}
    start = next(i for i, p in packages.items() if p["name"] == STUDIO)
    seen, todo = set(), [start]
    while todo:
        current = todo.pop()
        if current in seen:
            continue
        seen.add(current)
        for dep in nodes[current]["deps"]:
            if any(k["kind"] in (None, "build") for k in dep["dep_kinds"]):
                todo.append(dep["pkg"])
    crates = [packages[i] for i in seen if packages[i]["source"]]
    return sorted(crates, key=lambda p: (p["name"], p["version"]))


def render():
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked"],
        cwd=ROOT, check=True, capture_output=True, text=True,
    ).stdout
    crates = shipped_crates(json.loads(out))
    digest = lock_hash((ROOT / "Cargo.lock").read_text(encoding="utf-8"))
    lines = [
        "# Third-party Rust crates",
        "",
        f"<!-- {MARKER}{digest} -->",
        "<!-- Generated by tools/gen_third_party.py; do not edit by hand. -->",
        "",
        "| Crate | Version | Licence |",
        "| --- | --- | --- |",
    ]
    for p in crates:
        licence = (p["license"] or "see the crate's licence file").replace("|", "/")
        lines.append(f"| {p['name']} | {p['version']} | {licence} |")
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.name} is stale; run python -I tools/gen_third_party.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
