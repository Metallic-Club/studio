#!/usr/bin/env python3
"""Writes crates/metallic_studio/assets/THIRD_PARTY.md: the Rust crates Studio is built from and
their licences, read from `cargo metadata`. Studio shows the file on its "Third-party licences" screen.

    python tools/gen_third_party.py          # rewrite the file
    python tools/gen_third_party.py --check  # exit 1 when it is stale

A Rust test (src/licences.rs) walks metallic_studio's dependency graph in Cargo.lock and compares the
crate names and versions with this file, so it fails only when Studio's own dependencies change.
"""

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "crates" / "metallic_studio" / "assets" / "THIRD_PARTY.md"
STUDIO = "metallic_studio"


def shipped_crates(meta):
    """Registry crates reachable from Studio (the same set the test finds in Cargo.lock)."""
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    packages = {p["id"]: p for p in meta["packages"]}
    start = next(i for i, p in packages.items() if p["name"] == STUDIO)
    seen, todo = set(), [start]
    while todo:
        current = todo.pop()
        if current in seen:
            continue
        seen.add(current)
        for dep in nodes[current]["deps"]:
            todo.append(dep["pkg"])
    crates = [packages[i] for i in seen if packages[i]["source"]]
    return sorted(crates, key=lambda p: (p["name"], p["version"]))


def render():
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked"],
        cwd=ROOT, check=True, capture_output=True, text=True,
    ).stdout
    crates = shipped_crates(json.loads(out))
    lines = [
        "# Third-party Rust crates",
        "",
        "<!-- Generated by tools/gen_third_party.py; do not edit by hand. -->",
        "",
        "| Crate | Version | Licence |",
        "| --- | --- | --- |",
    ]
    for p in crates:
        licence = (p["license"] or "see the crate's licence file").replace("|", "/")
        lines.append(f"| {p['name']} | {p['version']} | {licence} |")
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.name} is stale; run python tools/gen_third_party.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
