//! Class discovery: finds every class, component and enum file under `src/` so that adding a class is one new file.
//!
//! A file takes part by exporting one or more of these items, at the start of a line:
//!
//! | Item                                  | Registers         |
//! |---------------------------------------|-------------------|
//! | `pub static CLASS: ClassDesc`         | a class           |
//! | `pub static COMPONENT: ComponentDesc` | a component       |
//! | `pub static ENUMS: &[EnumDesc]`       | a list of enums   |
//!
//! Every `.rs` file under `src/` (except `lib.rs`) becomes a module, with folders as nested modules, so
//! `src/world/lights/spot_light.rs` is `crate::world::lights::spot_light`. Files without a marker (shared helpers)
//! are compiled too. Folders must not contain a `mod.rs`: the folder already is the module.
//!
//! The output, `$OUT_DIR/classes.rs`, holds the module tree (`#[path]` modules) and the `ALL_CLASSES`,
//! `ALL_COMPONENTS` and `ALL_ENUMS` lists that `lib.rs` includes. A build script is used instead of linker-based
//! registration (`inventory`, `linkme`) because those are unreliable on mobile and consoles (ADR 0002).

use std::collections::BTreeMap;
use std::env;
use std::error::Error;
use std::fs;
use std::path::{Path, PathBuf};

const CLASS_MARKER: &str = "pub static CLASS:";
const COMPONENT_MARKER: &str = "pub static COMPONENT:";
const ENUMS_MARKER: &str = "pub static ENUMS:";

/// Files at the top of `src/` that are the crate itself, not class files.
const CRATE_FILES: &[&str] = &["lib.rs"];

type Result<T> = std::result::Result<T, Box<dyn Error>>;

/// One folder of the module tree.
#[derive(Default)]
struct Folder {
    /// Module name to the file's absolute path, with `/` separators.
    files: BTreeMap<String, String>,
    /// Module name to the subfolder.
    folders: BTreeMap<String, Folder>,
}

/// The module paths of every exported item, such as `crate::world::lights::spot_light::CLASS`.
#[derive(Default)]
struct Found {
    classes: Vec<String>,
    components: Vec<String>,
    enums: Vec<String>,
}

fn main() -> Result<()> {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR")?);
    let out_dir = PathBuf::from(env::var("OUT_DIR")?);
    let src = manifest.join("src");

    // Cargo scans a directory recursively, so adding, removing or editing any file under src/ re-runs this.
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=src");

    let mut root = Folder::default();
    let mut found = Found::default();
    scan(&src, &manifest, "crate", true, &mut root, &mut found)?;

    let mut code = String::from("// @generated by crates/classes/build.rs from the files under src/. Do not edit.\n\n");
    write_folder(&root, "src/", 0, &mut code);
    write_list(
        &mut code,
        "ALL_CLASSES",
        "Every `pub static CLASS` under `src/`.",
        "&::metallic_core::ClassDesc",
        &found.classes,
        "&",
    );
    write_list(
        &mut code,
        "ALL_COMPONENTS",
        "Every `pub static COMPONENT` under `src/`.",
        "&::metallic_core::ComponentDesc",
        &found.components,
        "&",
    );
    write_list(
        &mut code,
        "ALL_ENUMS",
        "Every `pub static ENUMS` list under `src/`.",
        "&[::metallic_core::EnumDesc]",
        &found.enums,
        "",
    );
    fs::write(out_dir.join("classes.rs"), code)?;
    Ok(())
}

/// Adds the files and folders in `dir` to `folder`, and the items they export to `found`.
fn scan(dir: &Path, manifest: &Path, module: &str, is_src: bool, folder: &mut Folder, found: &mut Found) -> Result<()> {
    let mut entries = fs::read_dir(dir)
        .map_err(|e| format!("cannot read {}: {e}", dir.display()))?
        .map(|entry| entry.map(|e| e.path()))
        .collect::<std::io::Result<Vec<PathBuf>>>()?;
    entries.sort();

    for path in entries {
        let shown = relative(&path, manifest);
        let file_name = path
            .file_name()
            .map(|n| n.to_string_lossy().into_owned())
            .unwrap_or_default();
        if path.is_dir() {
            let name = module_name(&file_name, &shown)?;
            let child = format!("{module}::{name}");
            scan(
                &path,
                manifest,
                &child,
                false,
                folder.folders.entry(name).or_default(),
                found,
            )?;
            continue;
        }
        let Some(stem) = file_name.strip_suffix(".rs") else {
            continue;
        };
        if is_src && CRATE_FILES.contains(&file_name.as_str()) {
            continue;
        }
        if stem == "mod" {
            return Err(format!("{shown}: folders are modules already; move this code into a named file").into());
        }
        let name = module_name(stem, &shown)?;
        let source = fs::read_to_string(&path).map_err(|e| format!("cannot read {shown}: {e}"))?;
        let item = |marker: &str, item: &str| exports(&source, marker).then(|| format!("{module}::{name}::{item}"));
        found.classes.extend(item(CLASS_MARKER, "CLASS"));
        found.components.extend(item(COMPONENT_MARKER, "COMPONENT"));
        found.enums.extend(item(ENUMS_MARKER, "ENUMS"));
        folder.files.insert(name, path.to_string_lossy().replace('\\', "/"));
    }

    if let Some(name) = folder.files.keys().find(|name| folder.folders.contains_key(*name)) {
        let shown = relative(dir, manifest);
        return Err(
            format!("{shown}: both `{name}.rs` and the folder `{name}/` would be module `{name}`; rename one").into(),
        );
    }
    Ok(())
}

/// Whether a line of `source` starts with `marker` (so a mention in a comment does not count).
fn exports(source: &str, marker: &str) -> bool {
    source.lines().any(|line| line.trim_start().starts_with(marker))
}

/// Checks that a file or folder name can be a module name.
fn module_name(name: &str, shown: &str) -> Result<String> {
    let mut chars = name.chars();
    let valid = chars.next().is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_');
    if valid {
        Ok(name.to_owned())
    } else {
        Err(format!("{shown}: `{name}` is not a valid module name; use snake_case letters, digits and `_`").into())
    }
}

/// `path` relative to the crate, with `/` separators, for messages.
fn relative(path: &Path, manifest: &Path) -> String {
    path.strip_prefix(manifest)
        .unwrap_or(path)
        .to_string_lossy()
        .replace('\\', "/")
}

/// Writes the modules of `folder`, nested like the folders.
fn write_folder(folder: &Folder, shown: &str, depth: usize, out: &mut String) {
    let pad = "    ".repeat(depth);
    for (name, path) in &folder.files {
        out.push_str(&format!("{pad}#[path = {path:?}]\n{pad}pub mod {name};\n"));
    }
    for (name, sub) in &folder.folders {
        let shown = format!("{shown}{name}/");
        let doc = format!("The classes under `{shown}`.");
        out.push_str(&format!("{pad}#[doc = {doc:?}]\n{pad}pub mod {name} {{\n"));
        write_folder(sub, &shown, depth + 1, out);
        out.push_str(&format!("{pad}}}\n"));
    }
}

/// Writes `pub(crate) static NAME: &[TY] = &[REF item, ...];`.
fn write_list(out: &mut String, name: &str, doc: &str, ty: &str, items: &[String], by_ref: &str) {
    out.push_str(&format!("\n#[doc = {doc:?}]\npub(crate) static {name}: &[{ty}] = &[\n"));
    for item in items {
        out.push_str(&format!("    {by_ref}{item},\n"));
    }
    out.push_str("];\n");
}
